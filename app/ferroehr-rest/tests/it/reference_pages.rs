//! The book's reference pages generated from the code: the AQL built-in
//! functions of `openehr-query` and the access refusal codes of the draft
//! access terminology.
//!
//! `the_book_holds_the_current_reference_pages` fails when a committed page
//! differs from what the code renders; `write_the_reference_pages` (ignored,
//! run with `cargo nextest run -p ferroehr-rest --test it --run-ignored only
//! reference_pages`) writes them again.

use std::path::PathBuf;

use openehr_query::ast::{DateTimeFunction, NumericFunction, StringFunction};
use openehr_rm::draft::access_control::terminology::{Refusal, Term as _};

const AQL_FUNCTIONS: &str = "website/book/src/reference/aql-functions.md";
const REFUSAL_CODES: &str = "website/book/src/reference/refusal-codes.md";

fn path(relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(relative)
}

// REUSE-IgnoreStart
fn banner(title: &str, intro: &str) -> String {
    [
        "<!-- @generated by the ferroehr-rest test reference_pages from the code. DO NOT EDIT. -->\n",
        "<!-- SPDX-FileCopyrightText: Cadasto B.V. -->\n",
        "<!-- SPDX-License-Identifier: BUSL-1.1 -->\n\n",
        "# ",
        title,
        "\n\n",
        intro,
        "\n\n",
    ]
    .concat()
}

// REUSE-IgnoreEnd

fn aql_functions() -> String {
    let mut out = banner(
        "AQL built-in functions",
        "**For:** integrators. Every built-in single-row function the AQL parser\n\
         accepts, by the group the AQL specification puts it in (QUERY, §Functions).\n\
         Names compare without regard to case. How to use them, the aggregates and\n\
         FerroEHR's extension functions are on [Querying with AQL](../querying-aql.md).",
    );
    out.push_str("| Function | Group |\n|---|---|\n");
    let rows = StringFunction::ALL
        .iter()
        .map(|f| (f.as_str(), "string"))
        .chain(NumericFunction::ALL.iter().map(|f| (f.as_str(), "numeric")))
        .chain(
            DateTimeFunction::ALL
                .iter()
                .map(|f| (f.as_str(), "date and time")),
        );
    for (name, group) in rows {
        out.push_str(&["| `", name, "` | ", group, " |\n"].concat());
    }
    out
}

fn refusal_codes() -> String {
    let mut out = banner(
        "Access refusal codes",
        "**For:** integrators and operators. Every code the access evaluator refuses\n\
         a request under, with the status the caller receives. A `403` names its code\n\
         in the problem's `detail`; a `404` answers as if the data did not exist and\n\
         names nothing. A `refused-confidentiality` answers `404` instead at a level\n\
         the access policy conceals. The access log records the code either way. What each step\n\
         decides is on [How FerroEHR decides access](../explanation/access-model.md).",
    );
    out.push_str("| Code | Answer |\n|---|---|\n");
    for refusal in Refusal::ALL {
        let answer = if refusal.is_invisible() { "404" } else { "403" };
        out.push_str(&["| `", refusal.code(), "` | ", answer, " |\n"].concat());
    }
    out
}

fn pages() -> [(&'static str, String); 2] {
    [
        (AQL_FUNCTIONS, aql_functions()),
        (REFUSAL_CODES, refusal_codes()),
    ]
}

#[test]
fn the_book_holds_the_current_reference_pages() {
    for (page, rendered) in pages() {
        let committed = std::fs::read_to_string(path(page)).expect("the reference page");
        assert!(
            committed == rendered,
            "{page} is out of date: run `cargo nextest run -p ferroehr-rest --test it \
             --run-ignored only reference_pages` and commit the page"
        );
    }
}

#[test]
#[ignore = "writes the book pages; run on purpose after changing the code they render"]
fn write_the_reference_pages() {
    for (page, rendered) in pages() {
        std::fs::write(path(page), rendered).expect("the reference page is written");
    }
}
