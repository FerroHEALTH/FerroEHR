//! The book's CLI reference, generated from the `clap` definition of
//! [`Cli`](ferroehr_server::Cli): one section per command with its long help.
//!
//! `the_book_holds_the_current_cli_reference` fails when the committed page
//! differs from what the definition renders; `write_the_cli_reference`
//! (ignored, run with `cargo nextest run -p ferroehr-server --run-ignored
//! only cli_reference`) writes the page again.

use std::path::PathBuf;

use clap::{Command, CommandFactory as _};
use ferroehr_server::Cli;

const PAGE: &str = "website/book/src/reference/cli.md";

/// The help width, fixed so the page does not depend on the terminal.
const WIDTH: usize = 100;

fn page_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(PAGE)
}

/// Appends the section of `command`, reached as `path`, and of each visible
/// subcommand below it.
fn section(out: &mut String, path: &str, command: &mut Command) {
    let help = command.render_long_help().to_string();
    for piece in ["## `", path, "`\n\n```text\n", help.trim_end(), "\n```\n\n"] {
        out.push_str(piece);
    }
    for sub in command
        .get_subcommands_mut()
        .filter(|sub| !sub.is_hide_set() && sub.get_name() != "help")
    {
        let below = [path, sub.get_name()].join(" ");
        section(out, &below, sub);
    }
}

// REUSE-IgnoreStart
/// The page the definition renders.
fn render() -> String {
    let mut command = Cli::command().term_width(WIDTH).max_term_width(WIDTH);
    command.build();
    let mut out = String::from(
        "<!-- @generated by the ferroehr-server test cli_reference from the clap \
         definition. DO NOT EDIT. -->\n\
         <!-- SPDX-FileCopyrightText: Cadasto B.V. -->\n\
         <!-- SPDX-License-Identifier: BUSL-1.1 -->\n\n\
         # Command-line reference\n\n\
         **For:** operators. Every command and option of the `ferroehr` binary,\n\
         as `ferroehr <command> --help` prints it. The guides to the commands are\n\
         on [CLI & production checklist](../installation/config-cli.md).\n\n\
         <!-- toc -->\n\n",
    );
    section(&mut out, "ferroehr", &mut command);
    out.trim_end().to_owned() + "\n"
}

// REUSE-IgnoreEnd

#[test]
fn the_book_holds_the_current_cli_reference() {
    let committed = std::fs::read_to_string(page_path()).expect("the CLI reference page");
    assert!(
        committed == render(),
        "{PAGE} is out of date: run `cargo nextest run -p ferroehr-server --run-ignored only \
         cli_reference` and commit the page"
    );
}

#[test]
#[ignore = "writes the book page; run on purpose after changing the CLI"]
fn write_the_cli_reference() {
    std::fs::write(page_path(), render()).expect("the CLI reference page is written");
}
