# Render the two EHDS pages FROM website/book/ehds.yaml.
#
# A readiness page typed by hand is wrong the first time a requirement's
# status changes, and wrong in the direction that matters: a stale "shipped"
# beside a requirement nothing implements is a false compliance claim on a
# public site. So the status lives in one committed file, both pages are a
# pure function of it, and the `ehds-pages` CI job re-renders and diffs.
#
# DETERMINISM. No clock, no HEAD commit, no network: two runs over an
# unchanged YAML produce identical bytes. The date a reader sees is the
# `regulation.read_on` field, which is when a human last read the regulation
# — a fact about the reading, not about the run.
#
# The legal text is NEVER restated as if it were binding. The YAML's
# `summary` fields are this project's paraphrase, the pages say so, and every
# page links the published regulation as the authority.
#
# Usage:
#   scripts/render/ehds-pages.sh            write both pages
#   scripts/render/ehds-pages.sh --check    fail when a committed page is stale
set -euo pipefail
cd "$(dirname "$0")/../.."

SRC="website/book/ehds.yaml"
READINESS="website/book/src/compliance/ehds-readiness.md"
TECHDOC="website/book/src/compliance/technical-documentation.md"
# The coverage matrix is injected into a HAND-WRITTEN page between markers,
# rather than owning a page of its own: the FHIR chapter is the place a reader
# already asks this question, and only the table is generated.
FHIR_PAGE="website/book/src/beyond-core/fhir.md"
FHIR_BEGIN="<!-- BEGIN generated: ehds-priority-categories -->"
FHIR_END="<!-- END generated: ehds-priority-categories -->"
SCRIPT="scripts/render/ehds-pages.sh"

CHECK=0
[[ "${1:-}" == "--check" ]] && CHECK=1

die() { printf 'ehds-pages: %s\n' "$1" >&2; exit 1; }

command -v yq >/dev/null || die "yq is not on PATH (mikefarah/yq v4)"
command -v jq >/dev/null || die "jq is not on PATH"
[[ -f "$SRC" ]] || die "$SRC does not exist"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

yq -o=json '.' "$SRC" > "$WORK/ehds.json" || die "$SRC is not valid YAML"

# Every status in the file must be one the vocabulary defines, or a typo
# becomes a silent blank cell on a compliance page.
bad="$(jq -r '
  [ (.requirements[].items[] | .status),
    (.components[] | .status) ]
  | map(select(. as $s | ["shipped","partial","planned","open"] | index($s) | not))
  | unique | join(", ")' "$WORK/ehds.json")"
[[ -z "$bad" ]] || die "unknown status value(s): $bad (expected shipped, partial, planned or open)"
bad="$(jq -r '
  [ .technical_documentation[].points[].source ]
  | map(select(. as $s | ["shipped","partial","open"] | index($s) | not))
  | unique | join(", ")' "$WORK/ehds.json")"
[[ -z "$bad" ]] || die "unknown source value(s): $bad (expected shipped, partial or open)"

reg_title="$(jq -r '.regulation.title' "$WORK/ehds.json")"
reg_url="$(jq -r '.regulation.url' "$WORK/ehds.json")"
reg_journal="$(jq -r '.regulation.journal' "$WORK/ehds.json")"
read_on="$(jq -r '.regulation.read_on' "$WORK/ehds.json")"

render_readiness() {
  cat <<HEADER
<!-- Generated by $SCRIPT from website/book/ehds.yaml. Do not edit by hand:
     the CI job re-renders and diffs, so an edit here is reverted with a red
     build. Change the YAML. -->

# EHDS readiness

The European Health Data Space regulation puts obligations on EHR systems in
its Chapter III: an EHR system must include two harmonised software
components, meet the essential requirements of Annex II, and carry technical
documentation and an EU declaration of conformity before it is placed on the
market or put into service.

This page states, requirement by requirement, what FerroEHR provides today.
It exists so an evaluator can see the real position rather than infer one,
and so the project has a checklist rather than an intention.

> [!WARNING]
> **No conformity assessment has been carried out.** No technical
> documentation has been drawn up under Article 37, no EU declaration of
> conformity exists under Article 39, and FerroEHR is not registered under
> Article 49. A status of "Shipped" below means the software provides the
> capability — it is not a claim of conformity, and nothing on this page is
> one.

## The regulation, and how to check this page against it

[$reg_title]($reg_url) — $reg_journal.

Every requirement identifier, heading and date on this page was read from
that published text on **$read_on**. The wording in the "Requirement" column
is this project's own paraphrase for navigation; the regulation is the
authority and its text governs. Where the two differ, the regulation is
right and this page is a defect worth reporting.

## When it applies

HEADER

  jq -r '.dates[] | "- **\(.when)** — \(.what)"' "$WORK/ehds.json"

  cat <<'COMPONENTS'

The last of those matters most here: a deployment that a health institution
runs for itself, or that is offered as a service, is *put into service* under
Article 26(2) rather than placed on the market.

## The two harmonised software components

Article 25(1) requires an EHR system to include both.

| Component | Status | Where it stands |
|---|---|---|
COMPONENTS

  jq -r '
    def badge: {shipped:"Shipped", partial:"Partial", planned:"Planned", open:"Open question"}[.];
    def issue_links: if (.issues // []) | length == 0 then "" else
      (" (" + ([.issues[] | "[#\(.)](https://github.com/FerroHEALTH/FerroEHR/issues/\(.))"] | join(", ")) + ")") end;
    .components[]
    | "| \(.name) | \(.status | badge)\(. | issue_links) | \(.note | gsub("\n"; " ")) |"
  ' "$WORK/ehds.json"

  cat <<'ANNEX2'

## Annex II — the essential requirements

The identifiers are the Annex's own. "Evidence" links what a reader can check
for themselves; "Gap" says what is missing when a row is not complete.

ANNEX2

  jq -r '
    def badge: {shipped:"Shipped", partial:"Partial", planned:"Planned", open:"Open question"}[.];
    def issue_links: if (.issues // []) | length == 0 then "" else
      ([.issues[] | "[#\(.)](https://github.com/FerroHEALTH/FerroEHR/issues/\(.))"] | join(", ")) end;
    def evidence: if (.evidence // []) | length == 0 then "—" else
      ([.evidence[] | "[\(.text)](\(.href))"] | join("; ")) end;
    def detail:
      [ (if .gap then "**Gap:** " + (.gap | gsub("\n"; " ")) else empty end),
        (if .question then "**Question:** " + (.question | gsub("\n"; " ")) else empty end),
        (if ((.issues // []) | length) > 0 then "Tracked in " + (. | issue_links) else empty end) ]
      | if length == 0 then "—" else join(" ") end;
    .requirements[]
    | ("### \(.group). \(.heading)\n",
       "| # | Requirement (our paraphrase) | Status | Evidence | Notes |",
       "|---|---|---|---|---|",
       (.items[] | "| \(.id) | \(.summary | gsub("\n"; " ")) | \(.status | badge) | \(. | evidence) | \(. | detail) |"),
       "")
  ' "$WORK/ehds.json"

  cat <<'QUESTIONS'
## Open questions

These decide whether Chapter III applies to a given deployment at all, and to
whom. They are questions this project has not answered, stated as questions.

QUESTIONS

  jq -r '
    def issue_links: if (.issues // []) | length == 0 then "" else
      (" Tracked in " + ([.issues[] | "[#\(.)](https://github.com/FerroHEALTH/FerroEHR/issues/\(.))"] | join(", ")) + ".") end;
    .open_questions[] | "- \(.question | gsub("\n"; " "))\(. | issue_links)"
  ' "$WORK/ehds.json"

  cat <<'FOOTER'

## Related

- [Technical documentation readiness](technical-documentation.md) — the Annex
  III elements, and what exists for each.
- [Shared responsibility](shared-responsibility.md) — which duties the
  software can carry and which belong to the deployment.
