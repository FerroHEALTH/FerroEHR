//! Whether a value of the current RM generation can be read by the released
//! generation's strict canonical-JSON reader (`openehr-rm`
//! `<current>/released/generated.rs`), decided over typed RM (#6002).
//!
//! The released reader refuses an attribute its class does not declare, a
//! mandatory attribute left out, and an object whose class does not conform to
//! the attribute's declared type in its own model. Every rule here is one of
//! those three, derived per class from the two generations' BMMs: an attribute
//! the released class lacks must be unset, an attribute the released class
//! makes mandatory must be set, and each object must be of a class the
//! released model has, conforming to the released declaration. A class the
//! released model lacks is never expressible. No openEHR specification
//! governs runtime generation selection: our own design.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::analyze::Model;
use crate::load::bmm::{BmmClass, BmmPropKind};
use crate::plan::overrides::back_reference;
use crate::plan::{Emission, JsonFieldKind, construction, decide};
use crate::render::emit::{GenFile, struct_generics};
use crate::render::emit_access::{Field, Holds, enum_parts, fields, walkable};
use crate::render::emit_walk::{WalkClass, WalkSchema, for_each_class};
use crate::render::generics::generic_header;

/// What the released model declares about one attribute.
struct Released {
    mandatory: bool,
    declared: String,
    multiple: bool,
    /// The declared type is a generic parameter of the class.
    generic: bool,
}

fn released_attributes(released: &Model, class: &str) -> Option<BTreeMap<String, Released>> {
    let c = released.get(class)?;
    // A mandatory attribute with a default (the `Interval` flags) reads as its
    // default when absent, so only a default-less one is required.
    let kinds: BTreeMap<String, JsonFieldKind> = released
        .json_fields(class)
        .into_iter()
        .filter(|f| f.default.is_none())
        .map(|f| (f.wire_name, f.kind))
        .collect();
    let mut out = BTreeMap::new();
    for rp in released.flattened_props(c) {
        let p = rp.prop;
        if back_reference(&rp.owner, &p.name).is_some() {
            continue;
        }
        let (declared, multiple) = match &p.kind {
            BmmPropKind::Single(t) => (t.root_name().to_owned(), false),
            // A byte buffer is inline base64 text on the canonical wire.
            BmmPropKind::Container { item, .. } if item.root_name() == "Octet" => {
                ("String".to_owned(), false)
            }
            BmmPropKind::Container { item, .. } => (item.root_name().to_owned(), true),
        };
        let mandatory = matches!(
            kinds.get(&p.name),
            Some(JsonFieldKind::Plain | JsonFieldKind::NonEmptyContainer)
        );
        let generic = released.is_generic_param(class, &declared);
        out.insert(
            p.name.clone(),
            Released {
                mandatory,
                declared,
                multiple,
                generic,
            },
        );
    }
    Some(out)
}

/// Emit the expressibility file for the current RM generation against the
/// `released` generation's model, whose module is `released_module`.
#[must_use]
pub(crate) fn emit_files(
    model: &Model,
    released: &Model,
    released_module: &str,
    schemas: &[WalkSchema<'_>],
) -> Vec<GenFile> {
    let walk = walkable(model);
    let released_used = released.used_as_type();
    let mut body = String::from(
        "// @generated by openehr-codegen (emit-validate) — DO NOT EDIT.\n\
         //! The generated half of [`super`]: one [`Expressible`] impl per RM and BASE\n\
         //! class, from the current and the released generations' BMMs.\n\n\
         #![allow(\n    \
         clippy::too_many_lines,\n    \
         clippy::nonminimal_bool,\n    \
         clippy::overly_complex_bool_expr,\n    \
         reason = \"one impl per class of the RM and BASE models; a generated check\"\n)]\n\n\
         use super::Expressible;\n\n",
    );
    for_each_class(model, schemas, |c| {
        let WalkClass {
            name,
            class,
            path,
            rust,
            emission,
            local,
            external,
        } = c;
        // The released model emits the class when it declares it and does
        // not skip it.
        let in_released = released
            .get(name)
            .is_some_and(|c| !matches!(decide(released, c, &released_used), Emission::Skip));
        let attrs = if in_released {
            released_attributes(released, name)
        } else {
            None
        };
        match emission {
            Emission::Struct => {
                let g = struct_generics(model, class);
                let f = fields(model, class, &g, &walk, local, external);
                emit_struct(
                    &mut body,
                    class,
                    &path,
                    &rust,
                    &g,
                    &f,
                    attrs.as_ref(),
                    released_module,
                );
            }
            Emission::PolyEnum(variants) => {
                let g = struct_generics(model, class);
                let f = fields(model, class, &g, &walk, local, external);
                emit_struct(
                    &mut body,
                    class,
                    &path,
                    &format!("{rust}Data"),
                    &g,
                    &f,
                    attrs.as_ref(),
                    released_module,
                );
                let (eg, idents) = enum_parts(model, name, &variants, Some(&rust));
                emit_enum(&mut body, &path, &rust, &eg, &idents);
            }
            Emission::Enum(variants) => {
                let (eg, idents) = enum_parts(model, name, &variants, None);
                emit_enum(&mut body, &path, &rust, &eg, &idents);
            }
            _ => {}
        }
    });
    vec![GenFile {
        path: "released/generated.rs".to_string(),
        body,
    }]
}

fn emit_enum(b: &mut String, path: &str, rust: &str, generics: &[String], idents: &[String]) {
    let (hdr, args) = generic_header(generics, "Expressible");
    let _ = write!(
        b,
        "impl{hdr} Expressible for {path}::{rust}{args} {{\n\
         fn rm_type(&self) -> &'static str {{\nmatch self {{\n"
    );
    for v in idents {
        let _ = writeln!(b, "Self::{v}(x) => x.rm_type(),");
    }
    b.push_str("}\n}\nfn expressible(&self) -> bool {\nmatch self {\n");
    for v in idents {
        let _ = writeln!(b, "Self::{v}(x) => x.expressible(),");
    }
    b.push_str("}\n}\n}\n\n");
}

#[expect(
    clippy::too_many_arguments,
    reason = "the class, its two field views and the naming it is emitted under"
)]
fn emit_struct(
    b: &mut String,
    class: &BmmClass,
    path: &str,
    rust: &str,
    generics: &[String],
    fields: &[Field],
    released: Option<&BTreeMap<String, Released>>,
    _released_module: &str,
) {
    let spec = &class.name;
    let (hdr, args) = generic_header(generics, "Expressible");
    let validated = construction::is_validated(spec);
    let mut rules: Vec<String> = Vec::new();
    match released {
        None => rules.push("false".to_string()),
        Some(attrs) => {
            for f in fields {
                let x = if validated {
                    format!("self.{}()", f.ident)
                } else {
                    format!("self.{}", f.ident)
                };
                let set = match (f.list, f.optional) {
                    (false, false) => None,
                    (false, true) => Some(format!("{x}.is_some()")),
                    (true, false) if f.non_empty => None,
                    (true, false) => Some(format!("!{x}.is_empty()")),
                    (true, true) => Some(format!("{x}.as_ref().is_some_and(|l| !l.is_empty())")),
                };
                let Some(r) = attrs.get(&f.wire) else {
                    // Undeclared in the released class: it must be absent.
                    rules.push(set.map_or_else(|| "false".to_string(), |s| format!("!{s}")));
                    continue;
                };
                if r.mandatory
                    && let Some(s) = &set
                {
                    rules.push(s.clone());
                }
                if r.multiple != f.list {
                    rules.push(
                        set.clone()
                            .map_or_else(|| "false".to_string(), |s| format!("!{s}")),
                    );
                    continue;
                }
                if f.holds != Holds::Object || validated {
                    continue;
                }
                let check = |v: &str| {
                    if r.generic {
                        format!("Expressible::expressible({v})")
                    } else {
                        format!("super::conforms({v}, {:?})", r.declared)
                    }
                };
                let rule = match (f.list, f.optional) {
                    (false, false) => check(&format!("&{x}")),
                    (false, true) => format!("{x}.as_ref().is_none_or(|v| {})", check("v")),
                    (true, false) => format!("{x}.iter().all(|v| {})", check("v")),
                    (true, true) => format!("{x}.iter().flatten().all(|v| {})", check("v")),
                };
                rules.push(rule);
            }
        }
    }
    let body = if rules.is_empty() {
        "true".to_string()
    } else {
        rules.join("\n&& ")
    };
    let _ = write!(
        b,
        "impl{hdr} Expressible for {path}::{rust}{args} {{\n\
         fn rm_type(&self) -> &'static str {{ {spec:?} }}\n\
         fn expressible(&self) -> bool {{\n{body}\n}}\n\
         }}\n\n"
    );
}
