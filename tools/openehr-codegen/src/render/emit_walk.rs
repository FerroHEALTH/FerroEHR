//! The typed RM-instance walk (`openehr-rm` `<generation>/validate/tree_generated.rs`):
//! one `Walk` impl per RM and BASE class, so the template-independent
//! validation passes of `validate::tree` run over typed RM with no
//! canonical-JSON value (#6002).
//!
//! A struct reports itself as one node (its RM class, its `archetype_node_id`
//! and `archetype_details` when it is a LOCATABLE, and its coded attributes for
//! the terminology slots), then visits every attribute that holds an RM or
//! BASE object, in BMM declaration order, under its wire name. An enum is
//! transparent: its payload is the node. No
//! openEHR specification governs the walk: our own design.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::analyze::{External, Model, emittable_specs};
use crate::load::bmm::BmmSchema;
use crate::plan::layout::{Ty, parse};
use crate::plan::overrides::{back_reference, class_binding};
use crate::plan::{Emission, decide};
use crate::render::emit::{GenFile, field_type, struct_generics, type_module_path};
use crate::render::naming;

/// The module path a class's type is named under, given the class.
pub(crate) type TypePath<'a> = Box<dyn Fn(&str) -> Option<String> + 'a>;

/// One schema whose classes get a walk impl, and how its types are named.
pub(crate) struct WalkSchema<'a> {
    /// The schema.
    pub schema: &'a BmmSchema,
    /// The module path a class's type is named under.
    pub path: TypePath<'a>,
    /// The emission scope the schema's own field types render in.
    pub external: &'a External,
}

/// The heads of the rendered types that hold an RM or BASE object.
fn walkable(model: &Model) -> BTreeSet<String> {
    let used = model.used_as_type();
    let mut out = BTreeSet::new();
    for (name, class) in model.class_iter() {
        match decide(model, class, &used) {
            Emission::Struct | Emission::Enum(_) => {
                out.insert(naming::type_name(name));
            }
            Emission::PolyEnum(_) => {
                out.insert(naming::type_name(name));
                out.insert(format!("{}Data", naming::type_name(name)));
            }
            _ => {}
        }
    }
    out
}

/// Emit the walk file for one RM generation: `own` is the generation's own
/// (re-emission augmented) schema, `deps` the BASE schemas its types reach.
#[must_use]
pub(crate) fn emit_files(model: &Model, schemas: &[WalkSchema<'_>]) -> Vec<GenFile> {
    let walk = walkable(model);
    let used = model.used_as_type();
    let mut seen = BTreeSet::new();
    let mut body = String::from(
        "// @generated by openehr-codegen (emit-validate) — DO NOT EDIT.\n\
         //! The typed RM-instance walk behind [`super::tree`]: one [`Walk`] impl per RM\n\
         //! and BASE class, generated from the BMM field view.\n\n\
         #![allow(\n    \
         clippy::too_many_lines,\n    \
         clippy::match_same_arms,\n    \
         reason = \"one impl per class of the RM and BASE models; a generated walk\"\n)]\n\n\
         use super::tree::{Coded as _, Node, Walk, Walker};\n\n",
    );
    for s in schemas {
        let local = emittable_specs(model, s.schema);
        for (name, class) in &s.schema.classes {
            if !seen.insert(name.clone()) {
                continue;
            }
            let Some(path) = (s.path)(name) else {
                continue;
            };
            let rust = naming::type_name(name);
            match decide(model, class, &used) {
                Emission::Struct => {
                    let generics = struct_generics(model, class);
                    emit_struct(
                        &mut body, model, class, &path, &rust, &generics, &walk, &local, s.external,
                    );
                }
                Emission::PolyEnum(variants) => {
                    let generics = struct_generics(model, class);
                    emit_struct(
                        &mut body,
                        model,
                        class,
                        &path,
                        &format!("{rust}Data"),
                        &generics,
                        &walk,
                        &local,
                        s.external,
                    );
                    let mut idents: Vec<String> =
                        variants.iter().map(|v| naming::type_name(v)).collect();
                    idents.push(rust.clone());
                    let enum_generics: Vec<String> = model
                        .used_generic_params(name)
                        .into_iter()
                        .map(|(n, _)| n)
                        .collect();
                    emit_enum(&mut body, &path, &rust, &enum_generics, &idents);
                }
                Emission::Enum(variants) => {
                    let idents: Vec<String> =
                        variants.iter().map(|v| naming::type_name(v)).collect();
                    let enum_generics: Vec<String> = model
                        .used_generic_params(name)
                        .into_iter()
                        .map(|(n, _)| n)
                        .collect();
                    emit_enum(&mut body, &path, &rust, &enum_generics, &idents);
                }
                _ => {}
            }
        }
    }
    vec![GenFile {
        path: "validate/tree_generated.rs".to_string(),
        body,
    }]
}

fn header(generics: &[String]) -> (String, String) {
    if generics.is_empty() {
        (String::new(), String::new())
    } else {
        let bounds: Vec<String> = generics
            .iter()
            .map(|g| format!("{g}: Walk + 'static"))
            .collect();
        (
            format!("<{}>", bounds.join(", ")),
            format!("<{}>", generics.join(", ")),
        )
    }
}

fn emit_enum(b: &mut String, path: &str, rust: &str, generics: &[String], idents: &[String]) {
    let (hdr, args) = header(generics);
    let _ = write!(
        b,
        "impl{hdr} Walk for {path}::{rust}{args} {{\n\
         fn walk(&self, w: &mut Walker) {{\n\
         match self {{\n"
    );
    for v in idents {
        let _ = writeln!(b, "Self::{v}(x) => x.walk(w),");
    }
    b.push_str("}\n}\n}\n\n");
}

/// The shape of one attribute: the object type it holds, whether it is a list,
/// optional, or boxed.
struct Shape {
    head: String,
    optional: bool,
    list: bool,
    boxed: bool,
}

fn shape(ty: &Ty) -> Option<Shape> {
    let mut t = ty;
    let mut optional = false;
    let mut list = false;
    let mut boxed = false;
    if t.head == "Option" {
        optional = true;
        t = t.args.first()?;
    }
    if t.head == "Box" {
        boxed = true;
        t = t.args.first()?;
    }
    if t.head == "Vec" || t.head == "NonEmptyVec" {
        list = true;
        t = t.args.first()?;
        if t.head == "Box" {
            boxed = true;
            t = t.args.first()?;
        }
    }
    Some(Shape {
        head: t.head.clone(),
        optional,
        list,
        boxed,
    })
}

#[expect(
    clippy::too_many_arguments,
    reason = "the field view threads the same resolution tables `field_type` takes"
)]
fn emit_struct(
    b: &mut String,
    model: &Model,
    class: &crate::load::bmm::BmmClass,
    path: &str,
    rust: &str,
    generics: &[String],
    walk: &BTreeSet<String>,
    local: &BTreeSet<String>,
    external: &External,
) {
    let subst: BTreeMap<String, String> = class_binding(&class.name);
    let (hdr, args) = header(generics);
    let mut visits = String::new();
    let mut coded = String::new();
    for rp in model.flattened_props(class) {
        let p = rp.prop;
        if back_reference(&rp.owner, &p.name).is_some() {
            continue;
        }
        let rendered = field_type(model, class, p, generics, &subst, local, external);
        let Some(sh) = parse(&rendered).as_ref().and_then(shape) else {
            continue;
        };
        let ident = naming::field_ident(&p.name);
        let wire = &p.name;
        // An overridden field holds a Rust type of its own, never an RM object.
        let holds_object = crate::plan::overrides::type_override(&class.name, &p.name).is_none()
            && (walk.contains(&sh.head) || generics.contains(&sh.head));
        if !sh.list && matches!(sh.head.as_str(), "CodePhrase" | "DvCodedText" | "DvText") {
            let _ = writeln!(coded, "{wire:?} => self.{ident}.coded(),");
        }
        if !holds_object {
            continue;
        }
        let deref = if sh.boxed { "&**" } else { "" };
        match (sh.list, sh.optional) {
            (false, false) => {
                let r = if sh.boxed { "&*" } else { "&" };
                let _ = writeln!(visits, "w.attr({wire:?}, {r}self.{ident});");
            }
            (false, true) => {
                let _ = writeln!(
                    visits,
                    "if let Some(v) = &self.{ident} {{ w.attr({wire:?}, {}v); }}",
                    if sh.boxed { "&**" } else { "" }
                );
            }
            (true, false) => {
                let _ = writeln!(
                    visits,
                    "for (i, v) in self.{ident}.iter().enumerate() {{ w.member({wire:?}, i, {deref}v); }}"
                );
            }
            (true, true) => {
                let _ = writeln!(
                    visits,
                    "for (i, v) in self.{ident}.iter().flatten().enumerate() {{ w.member({wire:?}, i, {deref}v); }}"
                );
            }
        }
    }
    let locatable = model.inherits(&class.name, "LOCATABLE") || class.name == "LOCATABLE";
    let (node_id, has_details, details_id) = if locatable {
        (
            "Some(self.archetype_node_id.as_str())",
            "self.archetype_details.is_some()",
            "self.archetype_details.as_ref().map(|d| d.archetype_id.value.as_str())",
        )
    } else {
        ("None", "false", "None")
    };
    let coded = if coded.is_empty() {
        "&|_| None".to_string()
    } else {
        format!("&|f: &str| match f {{\n{coded}_ => None,\n}}")
    };
    let _ = write!(
        b,
        "impl{hdr} Walk for {path}::{rust}{args} {{\n\
         fn walk(&self, w: &mut Walker) {{\n\
         w.node(\n&Node {{\n\
         rm_type: {spec:?},\n\
         value: self,\n\
         node_id: {node_id},\n\
         has_archetype_details: {has_details},\n\
         details_archetype_id: {details_id},\n\
         coded: {coded},\n\
         }},\n);\n\
         {visits}\
         }}\n}}\n\n",
        spec = class.name,
    );
}

/// The module path of a class emitted by `schema` inside the crate being
/// emitted, under generation `module`.
#[must_use]
pub(crate) fn local_path(module: &str, schema: &BmmSchema, class: &str) -> String {
    format!("crate::{module}::{}", type_module_path(schema, class))
}
