/// Emit `impl ToXml` for one [`XmlType`]. Public so the OPT emitter
/// (`emit_opt`) can reuse it over XSD-derived [`XmlType`]s.
pub(crate) fn emit_to_xml(
    b: &mut String,
    ty: &XmlType,
    path: &str,
    xsd: &XsdModel,
    unmatched: &mut Vec<(String, String)>,
) {
    match ty {
        XmlType::Struct {
            spec,
            rust,
            generics,
            fields,
        } => {
            let target = XmlTarget { spec, rust, path };
            emit_struct_to_xml(b, &target, generics, fields, xsd, unmatched);
        }
        XmlType::Enum {
            rust,
            generics,
            variants,
            ..
        } => {
            let (hdr, args) = generic_header(generics, "crate::xml::runtime::ToXml");
            let _ = write!(
                b,
                "impl{hdr} crate::xml::runtime::ToXml for {path}::{rust}{args} {{\n\
                 fn xml_type_name(&self) -> &'static str {{ match self {{\n"
            );
            for v in variants {
                let _ = writeln!(b, "{path}::{rust}::{}(x) => x.xml_type_name(),", v.ident);
            }
            b.push_str("} }\n");
            b.push_str("fn write_xml(&self, w: &mut crate::xml::runtime::XmlWriter, tag: &str, declared: Option<&str>) -> Result<(), crate::xml::runtime::XmlError> { match self {\n");
            for v in variants {
                let _ = writeln!(
                    b,
                    "{path}::{rust}::{}(x) => x.write_xml(w, tag, declared),",
                    v.ident
                );
            }
            b.push_str("} }\n}\n\n");
        }
        XmlType::Newtype { rust, .. } => {
            let _ = write!(
                b,
                "impl crate::xml::runtime::ToXml for {path}::{rust} {{\n\
                 fn write_xml(&self, w: &mut crate::xml::runtime::XmlWriter, tag: &str, _declared: Option<&str>) -> Result<(), crate::xml::runtime::XmlError> {{\n\
                 w.write_text_element(tag, &self.0.to_string())\n}}\n}}\n\n"
            );
        }
        XmlType::EnumLiterals {
            rust,
            string_backed,
            ..
        } => {
            // The wire token or integer as element text.
            let text = if *string_backed {
                "w.write_text_element(tag, self.as_str())"
            } else {
                "w.write_text_element(tag, &self.value().to_string())"
            };
            let _ = write!(
                b,
                "impl crate::xml::runtime::ToXml for {path}::{rust} {{\n\
                 fn write_xml(&self, w: &mut crate::xml::runtime::XmlWriter, tag: &str, _declared: Option<&str>) -> Result<(), crate::xml::runtime::XmlError> {{\n\
                 {text}\n}}\n}}\n\n"
            );
        }
    }
}

/// Emits `impl ToXml` for a struct in XSD order, or BMM order without
/// attributes when the XSD lacks it; an allowlisted BMM-only field trails.
fn emit_struct_to_xml(
    b: &mut String,
    target: &XmlTarget<'_>,
    generics: &[String],
    fields: &[XmlField],
    xsd: &XsdModel,
    unmatched: &mut Vec<(String, String)>,
) {
    let (hdr, args) = generic_header(generics, "crate::xml::runtime::ToXml");
    let (spec, rust, path) = (target.spec, target.rust, target.path);
    let by_wire: BTreeMap<&str, &XmlField> =
        fields.iter().map(|f| (f.wire_name.as_str(), f)).collect();
    let _ = write!(
        b,
        "impl{hdr} crate::xml::runtime::ToXml for {path}::{rust}{args} {{\n\
         fn xml_type_name(&self) -> &'static str {{ \"{spec}\" }}\n\
         fn write_xml(&self, w: &mut crate::xml::runtime::XmlWriter, tag: &str, declared: Option<&str>) -> Result<(), crate::xml::runtime::XmlError> {{\n\
         let mut __attrs: Vec<(&str, String)> = Vec::new();\n\
         if let Some(d) = declared {{ if d != \"{spec}\" {{ __attrs.push((\"xsi:type\", \"{spec}\".to_string())); }} }}\n"
    );
    let (attrs, mut elems): (Vec<String>, Vec<String>) = if let Some(shape) = xsd_shape(spec, xsd) {
        let (a, e) = xsd.flattened(shape);
        (
            a.iter().map(|x| x.name.clone()).collect(),
            e.iter().map(|x| x.name.clone()).collect(),
        )
    } else {
        (
            Vec::new(),
            fields.iter().map(|f| f.wire_name.clone()).collect(),
        )
    };
    for f in bmm_only_fields(spec, fields, xsd) {
        elems.push(f.wire_name.clone());
    }
    // A validated class's fields are `pub(crate)`: read through the accessor.
    let validated = construction::is_validated(spec);
    for aname in &attrs {
        match by_wire.get(aname.as_str()) {
            Some(f) => emit_write_attr(b, f, validated),
            None => unmatched.push((spec.to_owned(), aname.clone())),
        }
    }
    b.push_str("let mut __e = quick_xml::events::BytesStart::new(tag);\n");
    b.push_str("for (k, v) in &__attrs { __e.push_attribute((*k, v.as_str())); }\n");
    b.push_str("w.write_start(__e)?;\n");
    for ename in &elems {
        match by_wire.get(ename.as_str()) {
            Some(f) if !f.multiple && xml_value_wrapped(spec, &f.wire_name).is_some() => {
                emit_write_value_wrapped(b, spec, f, validated);
            }
            Some(f) => emit_write_field(b, f, validated),
            None => unmatched.push((spec.to_owned(), ename.clone())),
        }
    }
    b.push_str("w.write_end(tag)?;\nOk(())\n}\n}\n\n");
}

/// Pushes one XSD attribute onto the start tag's attribute list.
fn emit_write_attr(b: &mut String, f: &XmlField, validated: bool) {
    let read = if validated {
        format!("{}()", f.rust_name)
    } else {
        f.rust_name.clone()
    };
    let wire = &f.wire_name;
    if f.optional {
        let _ = writeln!(
            b,
            "if let Some(v) = &self.{read} {{ __attrs.push((\"{wire}\", v.to_string())); }}"
        );
    } else {
        let _ = writeln!(b, "__attrs.push((\"{wire}\", self.{read}.to_string()));");
    }
}

/// Writes one model `String` field in the `OBJECT_ID` shape its schema slot
/// names ([`xml_value_wrapped`]), with the delta as a `// NOTE:`.
fn emit_write_value_wrapped(b: &mut String, spec: &str, f: &XmlField, validated: bool) {
    let rust = if validated {
        format!("{}()", f.rust_name)
    } else {
        f.rust_name.clone()
    };
    let name = &f.wire_name;
    if let Some(citation) = xml_value_wrapped(spec, name) {
        let _ = writeln!(b, "// NOTE: {citation}");
    }
    if f.optional {
        let _ = writeln!(
            b,
            "if let Some(v) = &self.{rust} {{ crate::xml::runtime::write_value_wrapped(w, \"{name}\", v)?; }}"
        );
    } else {
        let _ = writeln!(
            b,
            "crate::xml::runtime::write_value_wrapped(w, \"{name}\", &self.{rust})?;"
        );
    }
}

fn emit_write_field(b: &mut String, f: &XmlField, validated: bool) {
    // A validated class reads its `pub(crate)` fields through the emitted
    // accessor (see the construction-door scheme in `plan::construction`).
    let accessor = |name: &str| {
        if validated {
            format!("{name}()")
        } else {
            name.to_owned()
        }
    };
    // `Hash` and `OrderedDict` share the `<name id="key">value</name>` shape.
    if f.target == "Hash" || f.target == "OrderedDict" {
        emit_write_map_field(b, f, &accessor(&f.rust_name));
        return;
    }
    let rust = accessor(&f.rust_name);
    let (name, rust, target) = (&f.wire_name, &rust, &f.target);
    if f.multiple && f.optional {
        // Zero occurrences is absence in XML, so `None` and `Some(vec![])` both write
        // nothing.
        let _ = writeln!(
            b,
            "if let Some(vs) = &self.{rust} {{ for v in vs {{ v.write_xml(w, \"{name}\", Some(\"{target}\"))?; }} }}"
        );
    } else if f.multiple {
        let _ = writeln!(
            b,
            "for v in &self.{rust} {{ v.write_xml(w, \"{name}\", Some(\"{target}\"))?; }}"
        );
    } else if f.optional {
        let _ = writeln!(
            b,
            "if let Some(v) = &self.{rust} {{ v.write_xml(w, \"{name}\", Some(\"{target}\"))?; }}"
        );
    } else {
        let _ = writeln!(
            b,
            "self.{rust}.write_xml(w, \"{name}\", Some(\"{target}\"))?;"
        );
    }
}

/// Emits the write half of a map-typed field: `Hash<String, String>` as
/// repeated `<name id="key">value</name>`; a complex map value is not on the
/// RM canonical-XML wire.
fn emit_write_map_field(b: &mut String, f: &XmlField, rust: &str) {
    let name = &f.wire_name;
    if f.map_value.as_deref() != Some("String") {
        let _ = writeln!(
            b,
            "// NOTE: Hash<String, {}> field `{rust}` is off the RM canonical-XML wire (resource metadata); not serialized.",
            f.map_value.as_deref().unwrap_or("?")
        );
        return;
    }
    if f.optional {
        let _ = writeln!(
            b,
            "if let Some(m) = &self.{rust} {{ for (k, v) in m {{ w.write_kv_element(\"{name}\", k, v)?; }} }}"
        );
    } else {
        let _ = writeln!(
            b,
            "for (k, v) in &self.{rust} {{ w.write_kv_element(\"{name}\", k, v)?; }}"
        );
    }
}

