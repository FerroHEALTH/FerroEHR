/// The schema closure the RM/BASE canonical-XML codec is generated from, named
/// in the refusal of an `xsi:type` it does not define.
pub(crate) const RM_XML_SCHEMA: &str = "the ITS-XML RM schemas";

/// Emits `impl FromXml` for one [`XmlType`]; an `xsi:type` outside `schema`'s
/// subtypes is refused.
pub(crate) fn emit_from_xml(
    b: &mut String,
    ty: &XmlType,
    path: &str,
    xsd: &XsdModel,
    door_env: Option<&XmlSchema<'_>>,
    schema: &str,
) {
    match ty {
        XmlType::Struct {
            spec,
            rust,
            generics,
            fields,
        } => {
            let target = XmlTarget { spec, rust, path };
            emit_struct_from_xml(b, &target, generics, fields, xsd, door_env);
        }
        XmlType::Enum {
            spec,
            rust,
            generics,
            dispatch,
            ..
        } => {
            let target = XmlTarget { spec, rust, path };
            emit_enum_from_xml(b, &target, generics, dispatch, schema);
        }
        XmlType::Newtype { rust, .. } => {
            let _ = write!(
                b,
                "impl crate::xml::runtime::FromXml for {path}::{rust} {{\n\
                 fn from_xml(reader: &mut crate::xml::runtime::XmlReader, start: &crate::xml::runtime::StartTag) -> Result<Self, crate::xml::runtime::XmlError> {{\n\
                 Ok({path}::{rust}(crate::xml::runtime::FromXml::from_xml(reader, start)?))\n}}\n}}\n\n"
            );
        }
        XmlType::EnumLiterals {
            rust,
            string_backed,
            ..
        } => {
            // Read the bare primitive back, then map it through the total
            // `from_wire`/`from_value` (an unknown token/integer becomes `Other`).
            let body = if *string_backed {
                format!(
                    "let __s = <::std::string::String as crate::xml::runtime::FromXml>::from_xml(reader, start)?;\nOk({path}::{rust}::from_wire(&__s))"
                )
            } else {
                format!(
                    "let __v = <i32 as crate::xml::runtime::FromXml>::from_xml(reader, start)?;\nOk({path}::{rust}::from_value(__v))"
                )
            };
            let _ = write!(
                b,
                "impl crate::xml::runtime::FromXml for {path}::{rust} {{\n\
                 fn from_xml(reader: &mut crate::xml::runtime::XmlReader, start: &crate::xml::runtime::StartTag) -> Result<Self, crate::xml::runtime::XmlError> {{\n\
                 {body}\n}}\n}}\n\n"
            );
        }
    }
}

/// The item one `FromXml` impl is emitted for: its openEHR spec name, its Rust
/// identifier, and the module path the identifier lives at.
struct XmlTarget<'a> {
    spec: &'a str,
    rust: &'a str,
    path: &'a str,
}

/// How one field of a struct is read back off the wire.
enum ReadShape {
    /// An XSD attribute on the type's own start tag.
    Attribute,
    /// `Hash<String, ComplexType>` — off-wire, so it reads back as the default.
    ComplexHash,
    /// A string map in the `StringDictionaryItem` shape, into an `IndexMap` when
    /// `ordered`, else a `BTreeMap`.
    StringHash { ordered: bool },
    /// A repeated child element.
    Multiple,
    /// A single child element.
    Single,
}

/// Classifies how one field of an XSD-covered struct is read back.
fn read_shape(f: &XmlField, attrs: &BTreeSet<String>) -> ReadShape {
    if attrs.contains(&f.wire_name) {
        return ReadShape::Attribute;
    }
    let is_dict = f.target == "Hash" || f.target == "OrderedDict";
    if is_dict && f.map_value.as_deref() == Some("String") {
        return ReadShape::StringHash {
            ordered: f.target == "OrderedDict",
        };
    }
    if f.target == "Hash" {
        return ReadShape::ComplexHash;
    }
    if f.multiple {
        return ReadShape::Multiple;
    }
    ReadShape::Single
}

/// Emits `impl FromXml` for a struct: accumulators, the child-element read
/// loop, and the construction that consumes them.
fn emit_struct_from_xml(
    b: &mut String,
    target: &XmlTarget<'_>,
    generics: &[String],
    fields: &[XmlField],
    xsd: &XsdModel,
    door_env: Option<&XmlSchema<'_>>,
) {
    let (hdr, args) = generic_header(generics, "crate::xml::runtime::FromXml");
    let attrs = attr_names(target.spec, xsd);
    let (path, rust) = (target.path, target.rust);
    // Never inlined, so a nested read keeps one node's accumulators per frame
    // (#5997).
    let _ = write!(
        b,
        "impl{hdr} crate::xml::runtime::FromXml for {path}::{rust}{args} {{\n\
         #[inline(never)]\n\
         fn from_xml(reader: &mut crate::xml::runtime::XmlReader, start: &crate::xml::runtime::StartTag) -> Result<Self, crate::xml::runtime::XmlError> {{\n"
    );
    if door_env.is_some_and(|s| s.schema.schema_name == crate::plan::layout::RM_SCHEMA) {
        b.push_str(
            "let _nesting = openehr_base::nesting::enter().map_err(crate::xml::runtime::XmlError::too_deep)?;\n",
        );
    }
    emit_read_accumulators(b, fields, &attrs);
    let unmodeled = xsd_unmodeled_elements(target.spec, fields, xsd);
    emit_read_loop(b, target.spec, fields, &attrs, &unmodeled);
    // Value expressions first, so a validating constructor takes the same ones.
    let values: Vec<(String, String)> = fields
        .iter()
        .map(|f| {
            (
                f.rust_name.clone(),
                read_expr(f, &attrs, target.spec, door_env),
            )
        })
        .collect();
    b.push_str(&crate::render::bound_presence::xml_locals(fields, acc_var));
    emit_read_construction(b, target, &values, door_env);
    b.push_str("}\n}\n\n");
}

/// Declares one accumulator local per element field, typed by inference.
fn emit_read_accumulators(b: &mut String, fields: &[XmlField], attrs: &BTreeSet<String>) {
    for f in fields {
        let var = acc_var(&f.rust_name);
        match read_shape(f, attrs) {
            ReadShape::Attribute | ReadShape::ComplexHash => {}
            ReadShape::StringHash { ordered: true } => {
                let _ = writeln!(b, "let mut {var} = indexmap::IndexMap::new();");
            }
            ReadShape::StringHash { ordered: false } => {
                let _ = writeln!(b, "let mut {var} = std::collections::BTreeMap::new();");
            }
            ReadShape::Multiple => {
                let _ = writeln!(b, "let mut {var} = Vec::new();");
            }
            ReadShape::Single => {
                let _ = writeln!(b, "let mut {var} = None;");
            }
        }
    }
}

/// The elements the XSD declares for `spec` that no field reads, which the
/// reader skips.
fn xsd_unmodeled_elements(spec: &str, fields: &[XmlField], xsd: &XsdModel) -> Vec<String> {
    let Some(shape) = xsd_shape(spec, xsd) else {
        return Vec::new();
    };
    let modeled: BTreeSet<&str> = fields.iter().map(|f| f.wire_name.as_str()).collect();
    let (_, elems) = xsd.flattened(shape);
    elems
        .into_iter()
        .map(|e| e.name)
        .filter(|name| !modeled.contains(name.as_str()))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect()
}

/// Emits the event loop that dispatches each child element; an element outside
/// the closed sequence is refused (XML Schema 1.1 Part 1 §3.4.4.2).
fn emit_read_loop(
    b: &mut String,
    spec: &str,
    fields: &[XmlField],
    attrs: &BTreeSet<String>,
    unmodeled: &[String],
) {
    b.push_str("loop { match reader.read()? {\n");
    b.push_str("crate::xml::runtime::XmlEvent::Start(__c) => match __c.name.as_str() {\n");
    for f in fields {
        let var = acc_var(&f.rust_name);
        let wire = &f.wire_name;
        match read_shape(f, attrs) {
            ReadShape::Attribute => {}
            // A complex-valued hash has no canonical-XML reading, but its element is
            // declared, so it is skipped rather than refused.
            ReadShape::ComplexHash => {
                let _ = writeln!(b, "\"{wire}\" => reader.skip_element()?,");
            }
            // StringDictionaryItem: `<name id="key">value</name>`, `id` use="required".
            ReadShape::StringHash { .. } => {
                let _ = writeln!(
                    b,
                    "\"{wire}\" => {{ let __k = __c.attr(\"id\").ok_or_else(|| reader.missing_start_attribute(\"StringDictionaryItem\", \"id\"))?.to_string(); let __v: String = crate::xml::runtime::FromXml::from_xml(reader, &__c)?; {var}.insert(__k, __v); }}"
                );
            }
            ReadShape::Multiple => {
                let _ = writeln!(
                    b,
                    "\"{wire}\" => {{ {var}.push(crate::xml::runtime::FromXml::from_xml(reader, &__c)?); }}"
                );
            }
            ReadShape::Single if xml_value_wrapped(spec, wire).is_some() => {
                let _ = writeln!(
                    b,
                    "\"{wire}\" => {{ {var} = Some(crate::xml::runtime::read_value_wrapped(reader, &__c)?); }}"
                );
            }
            ReadShape::Single => {
                let _ = writeln!(
                    b,
                    "\"{wire}\" => {{ {var} = Some(crate::xml::runtime::FromXml::from_xml(reader, &__c)?); }}"
                );
            }
        }
    }
    for name in unmodeled {
        let _ = writeln!(b, "\"{name}\" => reader.skip_element()?,");
    }
    for ext in xml_tool_extensions(spec) {
        let element = ext.element;
        let _ = writeln!(b, "// NOTE: {}", ext.citation);
        let _ = writeln!(
            b,
            "\"{element}\" => crate::xml::runtime::read_false_extension(reader, &__c, \"{spec}\")?,"
        );
    }
    let _ = writeln!(
        b,
        "_ => return Err(crate::xml::runtime::XmlError::UndeclaredChild {{ owner: \"{spec}\".to_owned(), child: __c.name.clone() }}),"
    );
    b.push_str("},\n");
    b.push_str("crate::xml::runtime::XmlEvent::End => break,\n");
    b.push_str("crate::xml::runtime::XmlEvent::Text(_) => {}\n");
    b.push_str("crate::xml::runtime::XmlEvent::Eof => return Err(crate::xml::runtime::XmlError::Parse(\"unexpected EOF\".into())),\n");
    b.push_str("} }\n");
}

/// The Rust expression that yields one field's value once the read loop has
/// finished; `door_env` resolves an enumeration-constant default marker.
fn read_expr(
    f: &XmlField,
    attrs: &BTreeSet<String>,
    spec: &str,
    door_env: Option<&XmlSchema<'_>>,
) -> String {
    match read_shape(f, attrs) {
        ReadShape::Attribute => attr_read_expr(f, spec),
        ReadShape::ComplexHash => "Default::default()".to_owned(),
        ReadShape::StringHash { .. } => {
            let var = acc_var(&f.rust_name);
            if f.optional {
                format!("if {var}.is_empty() {{ None }} else {{ Some({var}) }}")
            } else {
                var
            }
        }
        ReadShape::Multiple | ReadShape::Single => element_read_expr(f, spec, door_env),
    }
}

/// The value expression for a field carried as an XSD attribute.
fn attr_read_expr(f: &XmlField, spec: &str) -> String {
    let wire = &f.wire_name;
    if f.optional {
        format!("start.attr(\"{wire}\").map(|s| s.to_string())")
    } else {
        format!(
            "start.attr(\"{wire}\").ok_or_else(|| reader.missing_attribute(\"{spec}\", \"{wire}\"))?.to_string()"
        )
    }
}

/// The value expression for a field carried as child elements; a mandatory
/// field with a default falls back to it.
///
/// # Panics
/// When an enumeration-constant default is emitted without a door environment.
fn element_read_expr(f: &XmlField, spec: &str, door_env: Option<&XmlSchema<'_>>) -> String {
    let var = acc_var(&f.rust_name);
    let wire = &f.wire_name;
    let nonempty_new = format!(
        "openehr_base::containers::NonEmptyVec::new({var}).map_err(|__e| reader.invalid_content(::std::format!(\"element {wire}: {{__e}}\")))?"
    );
    if f.multiple && f.optional {
        // Zero occurrences reads back as `None`.
        let some = if f.nonempty {
            nonempty_new
        } else {
            var.clone()
        };
        return format!("if {var}.is_empty() {{ None }} else {{ Some({some}) }}");
    }
    if f.nonempty {
        // A `1..*` container goes through its own constructor, so a document
        // with zero occurrences is refused at parse.
        return nonempty_new;
    }
    if f.multiple || f.optional {
        return var;
    }
    if let Some(default) = &f.default {
        // A mandatory field archie omits (the Interval flags) reads its default when absent.
        let default = resolve_default(default, |marker| match door_env {
            Some(env) => door_param(env, marker),
            None => panic!(
                "{spec}.{wire}: enumeration default {marker} emitted without a door environment \
                 (an emit-opt closure bug)"
            ),
        });
        return format!("{var}.unwrap_or({default})");
    }
    format!("{var}.ok_or_else(|| reader.missing_child(\"{spec}\", \"{wire}\"))?")
}

/// Emits the read value's construction: the validating constructor, or a
/// struct literal.
fn emit_read_construction(
    b: &mut String,
    target: &XmlTarget<'_>,
    values: &[(String, String)],
    door_env: Option<&XmlSchema<'_>>,
) {
    let (path, rust) = (target.path, target.rust);
    let Some((params, fallible)) = construction::validated_ctor(target.spec) else {
        let _ = writeln!(b, "Ok({path}::{rust} {{");
        for (fname, expr) in values {
            let _ = writeln!(b, "{fname}: {expr},");
        }
        b.push_str("})\n");
        return;
    };
    let args = emit_ctor_bindings(b, target, params, values, door_env);
    if fallible {
        let _ = writeln!(
            b,
            "{path}::{rust}::new({args}).map_err(|__e| reader.invalid_content(::std::format!(\"{}: {{__e}}\")))",
            target.spec
        );
    } else {
        let _ = writeln!(b, "Ok({path}::{rust}::new({args}))");
    }
}

/// Binds each read value by field name to a local of the constructor's
/// declared parameter type and returns the argument list.
///
/// # Panics
/// If the construction map's parameter list and the XML field view disagree
/// in length or on a parameter name.
fn emit_ctor_bindings(
    b: &mut String,
    target: &XmlTarget<'_>,
    params: &[(&str, &str)],
    values: &[(String, String)],
    door_env: Option<&XmlSchema<'_>>,
) -> String {
    let spec = target.spec;
    assert_eq!(
        params.len(),
        values.len(),
        "construction map declares {} constructor parameter(s) for {spec}, \
         but the XML field view has {} field(s)",
        params.len(),
        values.len()
    );
    let mut names = Vec::new();
    for (i, (param, ty)) in params.iter().enumerate() {
        let Some((_, expr)) = values.iter().find(|(fname, _)| fname == param) else {
            panic!(
                "construction map parameter {param:?} of {spec} names no XML field \
                 (fields: {:?})",
                values.iter().map(|(f, _)| f).collect::<Vec<_>>()
            )
        };
        let ty = door_param_type(door_env, ty, spec);
        let _ = writeln!(b, "let __a{i}: {ty} = {expr};");
        names.push(format!("__a{i}"));
    }
    names.join(", ")
}

/// Resolves one constructor parameter's declared type against the door
/// environment.
///
/// # Panics
/// If a `@`-typed parameter is emitted without a door environment.
fn door_param_type(door_env: Option<&XmlSchema<'_>>, ty: &str, spec: &str) -> String {
    let Some(env) = door_env else {
        assert!(
            !ty.starts_with('@'),
            "door class {spec} with a @-typed parameter emitted without a door \
             environment (an emit-opt closure generating a door class is a \
             table/closure bug)"
        );
        return ty.to_owned();
    };
    door_param(env, ty)
}

/// Emits `impl FromXml` for an untagged enum: `xsi:type` dispatch, any other
/// `xsi:type` refused naming `schema`.
fn emit_enum_from_xml(
    b: &mut String,
    target: &XmlTarget<'_>,
    generics: &[String],
    dispatch: &[(String, String)],
    schema: &str,
) {
    let (hdr, args) = generic_header(generics, "crate::xml::runtime::FromXml");
    let (path, rust, spec) = (target.path, target.rust, target.spec);
    let self_ident = dispatch
        .iter()
        .find(|(x, _)| x == spec)
        .map(|(_, i)| i.clone());
    let _ = write!(
        b,
        "impl{hdr} crate::xml::runtime::FromXml for {path}::{rust}{args} {{\n\
         fn from_xml(reader: &mut crate::xml::runtime::XmlReader, start: &crate::xml::runtime::StartTag) -> Result<Self, crate::xml::runtime::XmlError> {{\n\
         match start.xsi_type() {{\n"
    );
    for (xsi, ident) in dispatch {
        let _ = writeln!(
            b,
            "Some(\"{xsi}\") => Ok({path}::{rust}::{ident}(crate::xml::runtime::FromXml::from_xml(reader, start)?)),"
        );
    }
    match self_ident {
        Some(ident) => {
            let _ = writeln!(
                b,
                "None => Ok({path}::{rust}::{ident}(crate::xml::runtime::FromXml::from_xml(reader, start)?)),"
            );
        }
        None => {
            let _ = writeln!(
                b,
                "None => Err(crate::xml::runtime::XmlError::Parse(\"{rust}: missing xsi:type\".into())),"
            );
        }
    }
    let _ = writeln!(
        b,
        "Some(other) => Err(crate::xml::runtime::XmlError::Parse(format!(\"{rust}: unknown xsi:type {{other}}: {schema} define no {spec} subtype of that name\"))),"
    );
    b.push_str("}\n}\n}\n\n");
}
