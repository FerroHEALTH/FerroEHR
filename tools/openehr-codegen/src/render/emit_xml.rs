//! XML emitter: `impl ToXml` and `impl FromXml` for the generated RM/BASE spec
//! types, into `openehr-its/src/xml/generated/`.
//!
//! The Rust facts come from [`Model::xml_types`], the wire shape from the
//! [`XsdModel`]. Reading dispatches child elements by name and polymorphic
//! slots by `xsi:type`.

use crate::analyze::Model;
use crate::load::bmm::BmmSchema;
use crate::load::xsd::XsdModel;
use crate::plan::construction;
use crate::plan::overrides::resolve_default;
use crate::plan::xml_overrides::{xml_ancestor_shape, xml_tool_extensions, xml_value_wrapped};
use crate::plan::{XmlField, XmlType};
use crate::render::emit_xml_guards::Guards;
use crate::render::generics::generic_header;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// One spec GENERATION paired with the crate+generation root its types are
/// named from.
pub(crate) struct XmlSchema<'a> {
    pub model: &'a Model,
    pub schema: &'a BmmSchema,
    /// The generation root every type of this schema is named under, e.g.
    /// `openehr_rm::v1_2`.
    pub root: &'a str,
    /// The generation's cross-crate index — resolves a `@SPEC` construction
    /// door parameter to the PAIRED dependency generation's defining module.
    pub external: &'a crate::analyze::External,
}

/// Resolves one construction-door parameter type: a `@SPEC` marker becomes the
/// generation-correct type path; any other string passes through.
///
/// # Panics
/// Panics when a marker names a class neither this generation nor its paired
/// dependencies emit.
fn door_param(s: &XmlSchema<'_>, ty: &str) -> String {
    let Some(spec) = ty.strip_prefix('@') else {
        return ty.to_owned();
    };
    let ident = crate::render::naming::type_name(spec);
    if s.schema.classes.contains_key(spec) {
        return format!(
            "{}::{}::{ident}",
            s.root,
            crate::render::emit::type_module_path(s.schema, spec)
        );
    }
    let module = s.external.module_of(spec).unwrap_or_else(|| {
        panic!(
            "construction door parameter @{spec}: neither the declaring generation nor its \
             paired dependency generations emit this class (a plan::construction table bug)"
        )
    });
    format!("{module}::{ident}")
}

/// The spec class an [`XmlType`] realizes — the key its Rust path is resolved
/// by.
fn xml_type_spec(ty: &XmlType) -> &str {
    match ty {
        XmlType::Struct { spec, .. }
        | XmlType::Enum { spec, .. }
        | XmlType::Newtype { spec, .. }
        | XmlType::EnumLiterals { spec, .. } => spec,
    }
}

/// Emits the whole generated impl file; `unmatched` receives the
/// `(type, element)` pairs the XSD declares and the BMM lacks.
///
/// # Errors
/// Fails if any LOCATABLE subtype would write `archetype_node_id` as an
/// element rather than an attribute.
pub(crate) fn emit_file(
    schemas: &[XmlSchema<'_>],
    xsd: &XsdModel,
    unmatched: &mut Vec<(String, String)>,
) -> Result<String, String> {
    let mut b = String::new();
    // One file-level `#![allow(…)]`: no single emission triggers every lint.
    b.push_str(
        "// @generated by openehr-codegen (emit-xml) — DO NOT EDIT.\n\
         // Canonical-XML `ToXml`/`FromXml` impls for the RM/BASE spec types.\n\n\
         #![allow(\n    \
         clippy::all,\n    \
         clippy::pedantic,\n    \
         clippy::nursery,\n    \
         unused_variables,\n    \
         unused_mut,\n    \
         unused_qualifications,\n    \
         unused_imports,\n    \
         reason = \"mechanically generated codec text: every runtime item is named \
         by its full path and every branch shape is emitted uniformly, so style \
         and unused-binding lints do not apply — the hand-written runtime carries \
         the lint bar\"\n\
         )]\n\
         use crate::xml::runtime::{ToXml, FromXml, XmlEvent, XmlError};\n\n",
    );
    let mut guards = Guards::default();
    for s in schemas {
        for ty in s.model.xml_types(s.schema) {
            guards.observe(&ty, xsd);
            let path = format!(
                "{}::{}",
                s.root,
                crate::render::emit::type_module_path(s.schema, xml_type_spec(&ty))
            );
            emit_to_xml(&mut b, &ty, &path, xsd, unmatched);
            emit_from_xml(&mut b, &ty, &path, xsd, Some(s), RM_XML_SCHEMA);
        }
    }
    guards.verdict(xsd)?;
    Ok(b)
}

/// A local accumulator variable name for a field. Strips the `r#` raw-identifier
/// prefix (`r#type` → `__type`) since `__r#type` is not a valid identifier.
fn acc_var(rust_name: &str) -> String {
    format!("__{}", rust_name.trim_start_matches("r#"))
}

/// The XSD type whose shape `spec` is written in: itself, else the ancestor
/// [`xml_ancestor_shape`] names.
pub(super) fn xsd_shape<'a>(spec: &'a str, xsd: &XsdModel) -> Option<&'a str> {
    if xsd.types.contains_key(spec) {
        return Some(spec);
    }
    xml_ancestor_shape(spec).filter(|a| xsd.types.contains_key(*a))
}

/// XSD attribute names for a type (empty if the type has no XSD shape).
pub(super) fn attr_names(spec: &str, xsd: &XsdModel) -> BTreeSet<String> {
    match xsd_shape(spec, xsd) {
        Some(shape) => xsd
            .flattened(shape)
            .0
            .iter()
            .map(|a| a.name.clone())
            .collect(),
        None => BTreeSet::new(),
    }
}

/// The fields of an XSD-covered struct that match no XSD attribute or element,
/// in BMM order; empty for a struct outside the XSD.
pub(super) fn bmm_only_fields<'a>(
    spec: &str,
    fields: &'a [XmlField],
    xsd: &XsdModel,
) -> Vec<&'a XmlField> {
    let Some(shape) = xsd_shape(spec, xsd) else {
        return Vec::new();
    };
    let (attrs, elems) = xsd.flattened(shape);
    let mut covered: BTreeSet<&str> = BTreeSet::new();
    for a in &attrs {
        covered.insert(a.name.as_str());
    }
    for e in &elems {
        covered.insert(e.name.as_str());
    }
    fields
        .iter()
        .filter(|f| !covered.contains(f.wire_name.as_str()))
        .collect()
}

